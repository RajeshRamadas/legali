"""Where uploaded files live: an S3-compatible bucket (AWS S3 or Cloudflare R2) when S3_BUCKET is set, else local disk.

Callers only deal in storage keys. Downloads are a redirect to a presigned URL for a bucket, or a file response from disk.
"""
import os
from functools import lru_cache
from pathlib import Path

from fastapi.responses import FileResponse, RedirectResponse, Response

from . import config

def backend() -> str:
    return "s3" if config.S3_BUCKET else "local"

@lru_cache
def _s3():
    import boto3  # Only needed when a bucket is configured.
    from botocore.config import Config

    return boto3.client(
        "s3", endpoint_url=config.S3_ENDPOINT_URL, region_name=config.S3_REGION,
        aws_access_key_id=config.S3_ACCESS_KEY_ID, aws_secret_access_key=config.S3_SECRET_ACCESS_KEY,
        config=Config(signature_version="s3v4", retries={"max_attempts": 3}),
    )

def _local_path(key: str) -> Path:
    root = Path(config.LOCAL_STORAGE_DIR).resolve()
    path = (root / key).resolve()
    # Keys are generated by us, but never let one point outside the storage folder.
    if root not in path.parents:
        raise ValueError("Invalid storage key")
    return path

def full_key(key: str) -> str:
    return f"{config.S3_KEY_PREFIX}{key}" if backend() == "s3" else key

def put(key: str, data: bytes, content_type: str) -> None:
    if backend() == "s3":
        _s3().put_object(Bucket=config.S3_BUCKET, Key=full_key(key), Body=data, ContentType=content_type)
        return
    path = _local_path(key)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".part")
    tmp.write_bytes(data)
    os.replace(tmp, path)

def get(key: str) -> bytes:
    if backend() == "s3":
        return _s3().get_object(Bucket=config.S3_BUCKET, Key=full_key(key))["Body"].read()
    return _local_path(key).read_bytes()

def delete(key: str) -> None:
    if backend() == "s3":
        _s3().delete_object(Bucket=config.S3_BUCKET, Key=full_key(key))
        return
    _local_path(key).unlink(missing_ok=True)

def _disposition(filename: str, inline: bool) -> str:
    from urllib.parse import quote

    ascii_name = filename.encode("ascii", "ignore").decode().replace('"', "") or "document"
    return f"{'inline' if inline else 'attachment'}; filename=\"{ascii_name}\"; filename*=UTF-8''{quote(filename)}"

def download_response(key: str, filename: str, content_type: str, inline: bool = False) -> Response:
    if backend() == "s3":
        url = _s3().generate_presigned_url(
            "get_object",
            Params={"Bucket": config.S3_BUCKET, "Key": full_key(key), "ResponseContentDisposition": _disposition(filename, inline), "ResponseContentType": content_type},
            ExpiresIn=60,
        )
        return RedirectResponse(url, status_code=302)
    path = _local_path(key)
    if not path.exists():
        return Response(status_code=404)
    return FileResponse(path, media_type=content_type, headers={"Content-Disposition": _disposition(filename, inline), "Cache-Control": "private, no-store"})
